//! Prints the component reference (`docs/COMPONENTS.md`) from the code:
//! kinds, file names, pins with their widths and editable properties.
//!
//! ```bash
//! cargo run -p lb_core --example component_reference > docs/COMPONENTS.md
//! ```

use lb_core::component::layout::layout;
use lb_core::component::{Category, Kind, PinDir};

fn main() {
    println!("# Component reference\n");
    println!("Generated by `cargo run -p lb_core --example component_reference`; do not edit by hand.\n");
    println!("Pins are listed in canonical orientation (facing east: inputs on the left, outputs on the right),");
    println!(
        "with the widths of a freshly placed component (data widths are configurable). Unconnected control inputs"
    );
    println!(
        "(`en`, `rst`, `pre`, `load`, carry/borrow in) take their inactive value; unconnected gate inputs are ignored.\n"
    );
    for cat in Category::ALL {
        println!("## {}\n", cat.name());
        println!("| Component | `kind` in files | Inputs | Outputs | Properties |");
        println!("| --- | --- | --- | --- | --- |");
        for kind in Kind::ALL.iter().copied().filter(|k| k.category() == cat) {
            let props = kind.default_props();
            let l = layout(kind, &props, None);
            let pins = |dir: PinDir| {
                let v: Vec<String> = l
                    .pins
                    .iter()
                    .filter(|p| p.dir == dir)
                    .map(|p| if p.width == 1 { format!("`{}`", p.name) } else { format!("`{}`[{}]", p.name, p.width) })
                    .collect();
                if v.is_empty() { "—".to_string() } else { v.join(", ") }
            };
            let keys: Vec<&str> = kind.prop_keys().iter().map(|k| k.name()).collect();
            let (ins, outs) = if kind == Kind::Subcircuit {
                ("its `Input` pins".to_string(), "its `Output` pins".to_string())
            } else {
                (pins(PinDir::In), pins(PinDir::Out))
            };
            println!("| {} | `{kind:?}` | {ins} | {outs} | {} |", kind.name(), keys.join(", "));
        }
        println!();
        if cat == Category::Io {
            println!("{IO_NOTES}");
        }
        if cat == Category::Displays {
            println!("{DISPLAY_NOTES}");
        }
    }
}

const IO_NOTES: &str = "\
* **Tunnel**: every tunnel with the same label in a circuit is connected, as if wired; the pin is
  passive, so the net can still have one or several (tri-state) drivers. Tunnels do not cross
  subcircuit boundaries (use Input and Output for that). A tunnel without a label, or the only one
  with its label, is reported as a warning.
* **Keyboard**: select it on the canvas and type; the keys are queued in a buffer of *Buffer size*
  characters, up to 4096 (Enter = line feed 10, Backspace = 8; Del deletes the component). `data` is the oldest character (7-bit ASCII,
  0 when empty) and `avail` is 1 while there is one; an active clock edge with `read` high (or
  unconnected) consumes it. `clear` empties the buffer at once.
";

const DISPLAY_NOTES: &str = "\
* **Number display**: shows its input on 7-segment digits in the chosen radix. *Digits* `Auto`
  fits the whole range of the width; with fewer digits the lowest ones are shown. Hex and binary
  are zero padded, decimal is blank padded; an unknown value shows dashes. One digit in hex is
  the hex display of older files, which are converted when loaded (`HexDisplay` in files).
* **7-segment display**: segments driven directly. With one digit each segment has its own pin
  (`a`-`g`, `dp`); with more digits each digit has an 8-bit input under it (bit 0 = `a` ... bit 6 =
  `g`, bit 7 = `dp`), `dig0` being the rightmost digit.
* **LED matrix**: *Columns x rows* LEDs; input `rowN` lights row N, its most significant bit on
  the left.
* **Text terminal**: on the active clock edge with `write` high, writes the ASCII character on
  `data` at the cursor. Printable characters (32-126) advance the cursor, line feed (10) and
  carriage return (13) start a new line, backspace (8) erases the previous character, form feed
  (12) clears the screen; text scrolls up past the last row. `clear` empties the screen at once.
* **Pixel screen**: on the active clock edge with `write` high, sets pixel (`x`, `y`) to `color`:
  1 bit (on/off), 8 bits `RRRGGGBB` or 24 bits `RRGGBB` (*Colors*). `clear` blanks the screen at
  once; pixels outside the screen are ignored.
";
